# =============================================================================
#  HOW TO MAKE YOUR OWN LEVEL
# =============================================================================
#
#  1. Copy one of the levels above and give it a new name, like  level_6.
#
#  2. A level is ALWAYS 20 rows tall and 30 letters wide. Count carefully!
#     (Tip: copy an existing level so the size is already correct.)
#
#  3. "Draw" your level using these letters:
#
#        .   empty space
#        #   grey platform   (always solid)
#        B   blue platform   (solid only in BLUE mode)
#        P   pink platform   (solid only in PINK mode)
#        ^   spike           (touch = respawn)
#        @   player start    (use this ONCE)
#        G   goal flag       (use this ONCE)
#        *   gem             (optional treasure)
#        C   checkpoint      (respawn point)
#
#  4. Add it to the LEVELS list at the bottom, like this:
#
#        LEVELS = [level_1, level_2, level_3, level_4, level_5, level_6]
#
#  5. Save the file and run the game again. That's it!
